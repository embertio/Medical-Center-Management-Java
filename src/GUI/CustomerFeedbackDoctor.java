    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String docID = jTextField1.getText().trim().toUpperCase();
        String docName =  jTextField2.getText().trim();
        String comment = jTextField3.getText().trim();
        String date = "";
        
        
        if(jDateChooser1.getDate()!=null){
            SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");
            date = sdf.format(jDateChooser1.getDate());
        }
        
        if(docID.isEmpty()||docName.isEmpty()||date.isEmpty()||comment.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please fill in all the fields!");
            jTextField1.requestFocus();
            return;
        }
        
        FeedbackDoctor feedback = new FeedbackDoctor(
            customer.getId(),
            customer.getName(),
            docID,
            docName,
            date,
            comment
        );
        
        try(FileWriter w = new FileWriter ("CustomerFeedbackDoctor.txt",true)){
            w.write(feedback.toString() + System.lineSeparator());
            JOptionPane.showMessageDialog(this, "Feedback saved sucessfully");
            
            model.addRow(new Object[]{feedback.getDocID(), feedback.getDocName(), feedback.getDate(), feedback.getComment()});
            
            jTextField1.setText("");
            jTextField2.setText("");
            jDateChooser1.setDate(null); 
            jTextField3.setText("");
            jTextField1.requestFocus();  
            
            
        }catch (IOException e){
            JOptionPane.showMessageDialog(this, "Error saving feedback!");
        }
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a feedback to delete!");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete this feedback?", "Confirm Delete", 
            JOptionPane.YES_NO_OPTION);
        
        if (confirm != JOptionPane.YES_OPTION) return;
        
        String docID = model.getValueAt(selectedRow, 0).toString();
        String docName = model.getValueAt(selectedRow, 1).toString();
        String date = model.getValueAt(selectedRow, 2).toString();
        String comment = model.getValueAt(selectedRow, 3).toString();
        String cusID = customer.getId();
        String cusName = customer.getName();
        
        FeedbackDoctor feedback = new FeedbackDoctor(
            cusID, cusName, docID, docName, date, comment
        );
        
        model.removeRow(selectedRow);
        
        try{
            List<String> lines = new ArrayList<>();
            try (BufferedReader br = new BufferedReader(new FileReader("CustomerFeedbackDoctor.txt"))){
                String line;
                while ((line = br.readLine())!=null){
                    if (!line.equals(feedback.toString())){
                        lines.add(line);
                    }
                }
            }
            
            try(FileWriter w = new FileWriter("CustomerFeedbackDoctor.txt",false)){//false open the file in overwrite mode,not append.
                for (String l : lines){
                    w.write(l+System.lineSeparator());
                }
            }
            
            JOptionPane.showMessageDialog(this, "Feedback deleted successfully!");
            
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jDateChooser1.setDate(null);
            jTextField1.requestFocus();
            
        }catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error deleting feedback!");
        }     
    }//GEN-LAST:event_jButton2ActionPerformed

