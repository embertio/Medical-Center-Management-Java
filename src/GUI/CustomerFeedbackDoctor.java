    private void setupFocusListeners() {
        jTextField1.addFocusListener(new java.awt.event.FocusAdapter() {
            
             @Override
             public void focusLost(java.awt.event.FocusEvent evt) {
                 autoDoctorIDtoName();
             }
        });
    }
    
    private void autoDoctorIDtoName(){
        String docID = jTextField1.getText().trim();
        
        if (docID.isEmpty()){
            jTextField2.setText("");
            return;
        }
        
        String docName = findDoctorName(docID);
        if(docName == null){
            JOptionPane.showMessageDialog(this, "Doctor Id not found");
            jTextField1.setText("");
            jTextField1.requestFocus();
            jTextField2.setText("");
        }
        
        jTextField2.setText(docName);
    }
    
    private String findDoctorName(String docID){
        try(BufferedReader br = new BufferedReader(new FileReader("Doctor.txt"))){
            String line;
            while ((line = br.readLine())!= null){
                String[] parts = line.split("\\|");
                if(parts.length == 6 && parts[0].trim().equalsIgnoreCase(docID)){
                    return parts[2].trim();
                }
            }
        }catch(IOException e){
            e.printStackTrace();
        }
        return null;
    }
    
    private void loadCustomerDoctorFeedback(){
        try(BufferedReader br = new BufferedReader(new FileReader("CustomerFeedbackDoctor.txt"))){
            String line;
            while((line = br.readLine())!=null){
                String[] parts = line.split("\\|");
                if (parts.length == 6){
                    FeedbackDoctor feedback = new FeedbackDoctor(
                            parts[0].trim(),
                            parts[1].trim(),
                            parts[2].trim(),
                            parts[3].trim(),
                            parts[4].trim(),
                            parts[5].trim()
                    );
                    
                    if(feedback.getCusID().equals(customer.getId())) {
                        model.addRow(new Object[]{feedback.getDocID(), feedback.getDocName(), feedback.getDate(), feedback.getComment()});
                    }
                }
            }
        }catch (IOException e) {
            e.printStackTrace();
        }
    }
    
    private void setupTableRowListener(){
        jTable1.addMouseListener(new java.awt.event.MouseAdapter(){
            public void mouseClicked(java.awt.event.MouseEvent evt){
                int selectedRow = jTable1.getSelectedRow();
                if(selectedRow != -1){
                    String docID = jTable1.getValueAt(selectedRow, 0).toString();
                    String docName = jTable1.getValueAt(selectedRow, 1).toString();
                    String dateStr = jTable1.getValueAt(selectedRow, 2).toString();
                    String comment = jTable1.getValueAt(selectedRow, 3).toString();
                    
                    jTextField1.setText(docID);
                    jTextField2.setText(docName);
                    
                    try{
                        Date date = new SimpleDateFormat("dd-MM-yyyy").parse(dateStr);
                        jDateChooser1.setDate(date);
                    }catch(java.text.ParseException e){
                        e.printStackTrace();
                        jDateChooser1.setDate(null);
                    }
                    
                    jTextField3.setText(comment);
                }
            }
        });
    }
    

    
    
    
    


