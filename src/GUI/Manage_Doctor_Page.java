    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        String searchId = searchIDField.getText().trim();
        if (searchId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter an ID to search.");
            return;
        }

        // create Manager object (or reuse existing one)
        Manager manager = new Manager("M001", "880101-10-1111", "John Manager", "Male", LocalDate.parse("1988-01-01"), "0112345678");

        // get search results table
        JTable searchResultTable = manager.searchDoctor(searchId);

        // check if found
        if (searchResultTable.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No record found with ID " + searchId + ".");

            // clear table in scrollpane
            ViewAllStaffScrollPane.setViewportView(new JTable());

            // clear all fields
            idField.setText("");
            icField.setText("");
            nameField.setText("");
            jDateChooser.setDate(new java.util.Date());
            contactField.setText("");
            maleButton.setSelected(false);
            femaleButton.setSelected(false);

        } else {
            // show table in scrollpane
            ViewAllStaffScrollPane.setViewportView(searchResultTable);

            // automatically fill your text fields with the first row (since only one record)
            int row = 0; // first row
            String id = searchResultTable.getValueAt(row, 0).toString();
            String ic = searchResultTable.getValueAt(row, 1).toString();
            String name = searchResultTable.getValueAt(row, 2).toString();
            String gender = searchResultTable.getValueAt(row, 3).toString();
            String dob = searchResultTable.getValueAt(row, 4).toString();
            String contact = searchResultTable.getValueAt(row, 5).toString();

            // set your fields
            idField.setText(id);
            icField.setText(ic);
            nameField.setText(name);
            contactField.setText(contact);
            
            try {
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
            java.util.Date date = sdf.parse(dob);
            jDateChooser.setDate(date);
            } catch (java.text.ParseException e) {
                jDateChooser.setDate(new java.util.Date());
            }

            // set gender buttons
            if (gender.equalsIgnoreCase("Male")) {
                maleButton.setSelected(true);
                femaleButton.setSelected(false);
            } else if (gender.equalsIgnoreCase("Female")) {
                femaleButton.setSelected(true);
                maleButton.setSelected(false);
            } else {
                maleButton.setSelected(false);
                femaleButton.setSelected(false);
            }
        }


    }//GEN-LAST:event_jButton4ActionPerformed

