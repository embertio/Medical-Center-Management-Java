    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String id = idField.getText().trim();
        String ic = icField.getText().trim();
        String name = nameField.getText().trim();
        String gender = maleButton.isSelected() ? maleButton.getText() :
                        (femaleButton.isSelected() ? femaleButton.getText() : "");
        java.util.Date selectedDate = jDateChooser.getDate();
        String contact = contactField.getText().trim();
        
        if (ic.isEmpty() || !ic.matches("\\d{12}")) { // 12 digits only
        JOptionPane.showMessageDialog(this, "IC must be 12 digits.");
        return;
        }

        if (contact.isEmpty() || !contact.matches("\\d{10}")) { // 11 digits only
            JOptionPane.showMessageDialog(this, "Contact number must be 10 digits.");
            return;
        }

        if (name.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name cannot be empty.");
            return;
         }

        if (gender.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a gender.");
            return;
        }

        if (selectedDate == null) {
            JOptionPane.showMessageDialog(this, "Please select a date of birth.");
            return;
        }
        
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
        String dob = sdf.format(selectedDate);
        
        Manager manager = new Manager("M001", "880101-10-1111", "John Manager", "Male", LocalDate.parse("1988-01-01"), "0112345678");
        boolean success = manager.createDoctor(ic, name, gender, dob, contact);

        if (success) {
            JOptionPane.showMessageDialog(this, "Doctor record saved successfully!");
            JTable refreshedTable = manager.viewAllDoctors();
            ViewAllStaffScrollPane.setViewportView(refreshedTable);
            // clear fields
            idField.setText("");
            icField.setText("");
            nameField.setText("");
            jDateChooser.setDate(null); 
            contactField.setText("");
            maleButton.setSelected(false);
            femaleButton.setSelected(false);

        } else {
            JOptionPane.showMessageDialog(this, "Failed to save doctor record.");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

