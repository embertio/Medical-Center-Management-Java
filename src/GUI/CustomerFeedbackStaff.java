    private void loadCustomerFeedbackStaff(){
        try (BufferedReader br = new BufferedReader(new FileReader("CustomerFeedbackStaff.txt"))){
            String line;
            while ((line = br.readLine()) != null){
                line = line.trim();
                if (line.isEmpty()) continue;
                String[] parts = line.split("\\|");
                if (parts.length >= 6) {
                    FeedbackStaff feedback = new FeedbackStaff(
                            parts[0].trim(),
                            parts[1].trim(),
                            parts[2].trim(),
                            parts[3].trim(),
                            parts[4].trim(),
                            parts[5].trim()           
                    );
                            
       
                    
                    if (feedback.getCusID().equals(customer.getId())){
                         model.addRow(new Object[]{feedback.getStaffID(), feedback.getStaffName(), feedback.getDate(), feedback.getComment()});
                    }
                }
            }
        }catch (IOException e) {
            e.printStackTrace();
        }
    }
    
    
    private void setupFocusListeners() {
        jTextField1.addFocusListener(new java.awt.event.FocusAdapter() {
            
             @Override
             public void focusLost(java.awt.event.FocusEvent evt) {
                 autoStaffIDtoName();
             }
        });
    }
    
    private void autoStaffIDtoName() {
        String staffID = jTextField1.getText().trim();
        
        if(staffID.isEmpty()){
            jTextField2.setText("");
            return;
        }
        
        String staffName = findStaffName(staffID);
        if (staffName == null){
            JOptionPane.showMessageDialog(this,"Staff ID not found!");
            jTextField1.setText("");
            jTextField1.requestFocus();
            jTextField2.setText("");
            return;
        }
        else{
            jTextField2.setText(staffName);
        }
          
    }
    
    private String findStaffName(String staffID) {
        try(BufferedReader br = new BufferedReader(new FileReader("Staffs.txt"))){
            String line;
            while ((line = br.readLine()) != null) {
                String[] parts = line.split("\\|");
                if (parts.length ==6 && parts[0].trim().equalsIgnoreCase(staffID)){ // if the file does consist 6 field and check whetehr their is matching StaffID
                    return parts[2].trim();
                }
            }
        }catch (IOException e) {
            e.printStackTrace();
        }
        return null;
    }
    
    private void setupTableRowListener() {
        jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int selectedRow = jTable1.getSelectedRow();
                if (selectedRow != -1) {
                    String staffID = jTable1.getValueAt(selectedRow, 0).toString();
                    String staffName = jTable1.getValueAt(selectedRow, 1).toString();
                    String dates = jTable1.getValueAt(selectedRow, 2).toString();
                    String comment = jTable1.getValueAt(selectedRow, 3).toString();
                    
                    jTextField1.setText(staffID);
                    jTextField2.setText(staffName);
                    
                    try{
                        Date date = new SimpleDateFormat("dd-MM-yyyy").parse(dates);
                        jDateChooser1.setDate(date);
                    }catch(java.text.ParseException e) {
                        e.printStackTrace();
                        jDateChooser1.setDate(null);
                    }
                    
                    jTextField3.setText(comment);
                }
            }
        });
    }

