    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String staffID = jTextField1.getText().trim().toUpperCase();
        String staffName = jTextField2.getText().trim();
        String comment = jTextField3.getText().trim();
        String date = "";
        
        
        if(jDateChooser1.getDate()!=null){
            SimpleDateFormat sdf = new SimpleDateFormat("dd-MM-yyyy");
            date = sdf.format(jDateChooser1.getDate());
        }

        
        if(staffID.isEmpty() || staffName.isEmpty() || date.isEmpty() || comment.isEmpty()){
            JOptionPane.showMessageDialog(this, "Please fill in all fields!");
            return;
        }
 
        
        String cusID = customer.getId();
        String cusName = customer.getName();
        
        FeedbackStaff feedback = new FeedbackStaff(
            cusID, cusName, staffID, staffName, date, comment
        );
        
        try(FileWriter w = new FileWriter("CustomerFeedbackStaff.txt",true)){//append mode to true
            w.write(feedback.toString() + System.lineSeparator());
            JOptionPane.showMessageDialog(this, "Feedback saved successfully!");
            
            model.addRow(new Object[]{feedback.getStaffID(), feedback.getStaffName(), feedback.getDate(), feedback.getComment()});
            
            jTextField1.setText("");
            jTextField2.setText("");
            jDateChooser1.setDate(null);
            jTextField3.setText("");
            jTextField1.requestFocus();
                       
        }catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving feedback!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int selectedrow = jTable1.getSelectedRow();
        if(selectedrow == -1){
            JOptionPane.showMessageDialog(this, "Please select a feedback to delete!");
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete this feedback?", "Confirm Delete", 
            JOptionPane.YES_NO_OPTION);

        if (confirm != JOptionPane.YES_OPTION) return;
        
        String staffID = model.getValueAt(selectedrow, 0).toString();
        String staffName = model.getValueAt(selectedrow, 1).toString();
        String date = model.getValueAt(selectedrow, 2).toString();
        String comment = model.getValueAt(selectedrow, 3).toString();
        String cusID = customer.getId();
        String cusName = customer.getName();
        
        FeedbackStaff feedback = new FeedbackStaff(
            cusID, cusName, staffID, staffName, date, comment
        );
        
        model.removeRow(selectedrow);
        
        try{
            List<String> lines = new ArrayList<>();
            try(BufferedReader br = new BufferedReader(new FileReader("CustomerFeedbackStaff.txt"))){
                String line;
                while ((line = br.readLine())!=null){
                    if(!line.equals(feedback.toString())){
                        lines.add(line);
                    }
                }
            }
            
            try(FileWriter w = new FileWriter("CustomerFeedbackStaff.txt",false)){//false overwrite the file
                for(String l : lines){
                    w.write(l + System.lineSeparator());
                }
            }
            JOptionPane.showMessageDialog(this, "Feedback deleted successfully!");
            
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jDateChooser1.setDate(null);
            jTextField1.requestFocus();
            
        }catch(IOException e){
            JOptionPane.showMessageDialog(this, "Error deleting feedback!");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

